"""
Label quality taxonomy and training eligibility classification.
Distinguishes solver-certified optima from sub-optimal incumbents, fallbacks, and solver failures.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Optional, Tuple


class LabelQuality(str, Enum):
    """
    Taxonomy of optimization label quality.
    
    SOLVER_CERTIFIED: Solver-declared optimal within configured tolerance.
    FEASIBLE_WITH_GAP: Incumbent solution found, but MIP gap exceeds certified threshold.
    NO_INCUMBENT: Solver terminated (e.g. time limit) without discovering any feasible integer solution.
    INFEASIBLE: Model proven mathematically infeasible under given constraints.
    FAILED: Solver crashed, encountered numerical breakdown, or unbounded.
    FALLBACK: Action generated by heuristic or no-trade fallback policy.
    """
    SOLVER_CERTIFIED = "SOLVER_CERTIFIED"
    FEASIBLE_WITH_GAP = "FEASIBLE_WITH_GAP"
    NO_INCUMBENT = "NO_INCUMBENT"
    INFEASIBLE = "INFEASIBLE"
    FAILED = "FAILED"
    FALLBACK = "FALLBACK"


@dataclass(frozen=True)
class LabelQualityConfig:
    """
    Configuration parameters determining label classification and training eligibility.
    
    Attributes:
        certified_gap_tol: Maximum MIPGap to declare SOLVER_CERTIFIED (e.g. 1e-4).
        max_trainable_gap: Maximum MIPGap allowed for training if allow_gap_training is True.
        allow_gap_training: Whether FEASIBLE_WITH_GAP instances with gap <= max_trainable_gap are eligible.
    """
    certified_gap_tol: float = 1e-4
    max_trainable_gap: float = 1e-4
    allow_gap_training: bool = False


def classify_label_quality(
    solver_status: str,
    is_optimal: bool,
    is_feasible: bool,
    mip_gap: Optional[float] = None,
    used_fallback: bool = False,
    config: Optional[LabelQualityConfig] = None,
) -> Tuple[LabelQuality, bool]:
    """
    Classify the solution quality and decide if the instance is eligible for supervised training.

    Args:
        solver_status: Gurobi status string (e.g. 'OPTIMAL', 'TIME_LIMIT', 'INFEASIBLE').
        is_optimal: Whether solver returned GRB.OPTIMAL.
        is_feasible: Whether at least one feasible integer incumbent exists (SolCount > 0).
        mip_gap: Relative MIP gap from solver.
        used_fallback: Flag indicating if a non-solver fallback policy was applied.
        config: LabelQualityConfig determining thresholds.

    Returns:
        Tuple of (LabelQuality enum, is_trainable_label: bool).
    """
    cfg = config or LabelQualityConfig()

    # Rule 1: Fallback actions are NEVER canonical teacher labels
    if used_fallback:
        return LabelQuality.FALLBACK, False

    # Rule 2: Explicit infeasibility
    if solver_status == "INFEASIBLE":
        return LabelQuality.INFEASIBLE, False

    # Rule 3: Solver failure or unboundedness
    if solver_status in ("FAILED", "UNBOUNDED", "INF_OR_UNBD"):
        return LabelQuality.FAILED, False

    # Rule 4: Infeasible termination (e.g. TimeLimit without finding any incumbent)
    if not is_feasible:
        if solver_status in ("TIME_LIMIT", "SUBOPTIMAL", "ITERATION_LIMIT", "NODE_LIMIT"):
            return LabelQuality.NO_INCUMBENT, False
        return LabelQuality.FAILED, False

    # Rule 5: Feasible incumbent exists
    # Check if certified
    if is_optimal or (mip_gap is not None and mip_gap <= cfg.certified_gap_tol):
        return LabelQuality.SOLVER_CERTIFIED, True

    # Feasible with non-certified gap
    is_trainable = bool(
        cfg.allow_gap_training
        and mip_gap is not None
        and mip_gap <= cfg.max_trainable_gap
    )
    return LabelQuality.FEASIBLE_WITH_GAP, is_trainable
